package com.operators.OperatorImportantQues;

public class SwapTwoNumber {
    static void main(String[] args) {


        int num1 = 333;
        int num2 = 444;
        int temp ;

        System.out.println("After swaping two numbers is "+num1+" and "+ num2);

        temp = num1;
        num1 = num2;
        num2 = temp;
        System.out.println("After swaping two numbers is "+num1+" and "+ num2);
    }
}
